"""Generated ``pipeline.py``: reproduce a dataset version from its original file (Part E).

The module is standalone (pandas, NumPy, pyarrow, scikit-learn, SciPy; openpyxl, xlrd and
defusedxml for spreadsheets). It embeds, verbatim:
1. DataMedic's parsing code (``engine/errors``, ``table``, ``io/readers``, ``hashing``,
   ``preview``, ``io/parse``) with their internal imports removed (these modules share one
   namespace; their top-level names do not collide, which ``render_pipeline`` checks);
2. the preprocessing runtime (as ``codegen.render_steps`` does);
3. one function per committed step (the existing per-op templates), grouped per committed
   transformation, in lineage order. Reverted versions replay the chain of the version they
   restore, so undone transformations are never replayed;
4. the version's model-stage specification as a separate in-fold function
   (``model_preprocess`` / ``prepare_training``), never applied to the saved data.

``main`` parses the original exactly as ingest did (refusing to continue if the detected
parse options differ from the recorded ones), applies every committed transformation
(fitted on all rows, as committed), stores each intermediate version through Parquet like
the platform, writes the result and prints its content hash. No stored object is read, no
learned value is embedded, nothing is unpickled, and user text appears only as ``repr`` of
JSON primitives.
"""

import ast
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from datamedic.engine import ENGINE_VERSION
from datamedic.engine.preprocess.codegen import (
    CodegenError,
    _step_source,
    _training_source,
    literal,
    runtime_source,
)
from datamedic.engine.preprocess.validate import ValidatedStep

# Embedded by file path (no import), so rendering needs no data libraries.
ENGINE_DIR = Path(__file__).resolve().parents[1]
PARSE_MODULES = (
    "errors.py",
    "table.py",
    "io/readers.py",
    "hashing.py",
    "preview.py",
    "io/parse.py",
)


@dataclass(frozen=True)
class Commit:
    version_number: int
    steps: Sequence[ValidatedStep]


def _strip_internal_imports(source: str) -> str:
    tree = ast.parse(source)
    lines = source.splitlines(keepends=True)
    drop: set[int] = set()
    for node in tree.body:
        if isinstance(node, ast.ImportFrom) and (node.module or "").startswith("datamedic"):
            drop.update(range(node.lineno - 1, (node.end_lineno or node.lineno)))
        elif isinstance(node, ast.Import) and any(
            a.name.startswith("datamedic") for a in node.names
        ):
            raise CodegenError("embedded module imports the datamedic package")
    return "".join(line for i, line in enumerate(lines) if i not in drop)


def _top_level_names(source: str) -> dict[str, str]:
    out = {}
    for node in ast.parse(source).body:
        if isinstance(node, ast.FunctionDef | ast.ClassDef):
            out[node.name] = ast.unparse(node)
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    out[t.id] = ast.unparse(node)
    return out


def embedded_sources() -> str:
    """Parsing modules then the runtime, in one namespace. Refuses any top-level name that
    two modules define differently."""
    parts, seen = [], _top_level_names('ROW_ID = "_dm_row_id"')
    sources = [
        (name, (ENGINE_DIR / name).read_text(encoding="utf-8")) for name in PARSE_MODULES
    ] + [("preprocess/runtime.py", runtime_source())]
    for module, text in sources:
        src = _strip_internal_imports(text)
        for name, code in _top_level_names(src).items():
            if name in seen and seen[name] != code:
                raise CodegenError(f"embedded modules define {name!r} differently")
            seen[name] = code
        parts.append(f"\n\n# ---- engine/{module} (DataMedic engine {ENGINE_VERSION}) ----\n")
        parts.append(src)
    return "".join(parts)


_HEADER = '''"""DataMedic pipeline.py: reproduces dataset version {version} from its original file.

Generated by DataMedic engine {engine}. Usage:

    python pipeline.py ORIGINAL_FILE OUTPUT.parquet

Parses the original file exactly as DataMedic did, applies the committed transformations in
order (each fitted on all rows of its source version, as committed) and writes the version.
Committed transformations: {commits}. Versions restored by a revert replay the chain of the
version they restore.

The modelling specification (model-stage steps) is NOT applied to the output. Use
model_preprocess(train_df, df) and prepare_training(train_df) inside each training fold.

Recorded library versions: {libraries}
"""

import sys

ROW_ID = "_dm_row_id"
'''

_MAIN = '''

FORMAT = {fmt}
DECLARED_EXTENSION = {ext}
EXPECTED_PARSE_OPTIONS = {options}
SEED = {seed}
COMMITS = ({commits})
MODEL_STEPS = ({model})
TRAINING_STEP = {training}


def _through_parquet(df):
    import io

    import pandas as pd

    buf = io.BytesIO()
    write_frame(df, buf)
    return pd.read_parquet(io.BytesIO(buf.getvalue()), engine="pyarrow")


def load_original(path):
    """Version 0: the canonical table parsed from the original file."""
    from pathlib import Path

    parsed = parse_original(Path(path), FORMAT, DECLARED_EXTENSION)
    if parsed.parse_options != EXPECTED_PARSE_OPTIONS:
        raise SystemExit("The file parses with different options than the recorded original.")
    return parsed.table.frame


def build(path):
    """The version's table and its content hash."""
    df = load_original(path)
    if not COMMITS:
        return df, content_hash(df).hex()
    df = _through_parquet(df)
    for steps in COMMITS:
        for make_step in steps:
            df = make_step(df)(df)
        df = _through_parquet(df)
    return df, content_hash(df).hex()


def model_preprocess(fit_df, df=None):
    """The modelling specification: fit on training rows (fit_df), apply to any rows."""
    if df is None:
        df = fit_df
    for make_step in MODEL_STEPS:
        apply = make_step(fit_df)
        fit_df, df = apply(fit_df), apply(df)
    return df


def prepare_training(fit_df):
    """Training rows after the modelling specification, resampled or weighted if specified."""
    df = model_preprocess(fit_df)
    return df if TRAINING_STEP is None else TRAINING_STEP(df)


def main(argv):
    if len(argv) != 3:
        raise SystemExit("usage: python pipeline.py ORIGINAL_FILE OUTPUT.parquet")
    df, digest = build(argv[1])
    write_frame(df, argv[2])
    print(digest)


if __name__ == "__main__":
    main(sys.argv)
'''


def render_pipeline(
    *,
    version_number: int,
    fmt: str,
    declared_extension: str,
    parse_options: dict[str, Any],
    commits: Sequence[Commit],
    model_steps: Sequence[ValidatedStep],
    seed: int,
    libraries: dict[str, str],
) -> str:
    if not isinstance(seed, int) or isinstance(seed, bool):
        raise CodegenError("seed must be an integer")
    parts = [
        _HEADER.format(
            version=int(version_number),
            engine=ENGINE_VERSION,
            commits=", ".join(f"version {int(c.version_number)}" for c in commits) or "none",
            libraries=", ".join(
                f"{k} {v}"
                for k, v in sorted(libraries.items())
                if k.replace("-", "").replace("_", "").isalnum()
                and str(v).replace(".", "").replace("+", "").isalnum()
            ),
        ),
        embedded_sources(),
    ]
    number = 0
    groups = []
    for c in commits:
        names = []
        for v in c.steps:
            if v.spec.stage == "model":
                raise CodegenError("a committed transformation cannot contain model-stage steps")
            number += 1
            parts.append(_step_source(number, v))
            names.append(f"step_{number}")
        groups.append("(" + ", ".join(names) + ("," if len(names) == 1 else "") + ")")
    model_names, training = [], "None"
    for v in model_steps:
        number += 1
        parts.append(_step_source(number, v))
        model_names.append(f"step_{number}")
        if v.spec.kind == "training_only":
            parts.append(_training_source(v))
            training = "training_step"
    parts.append(
        _MAIN.format(
            fmt=literal(fmt),
            ext=literal(declared_extension),
            options=literal(parse_options),
            seed=literal(seed),
            commits=", ".join(groups) + ("," if len(groups) == 1 else ""),
            model=", ".join(model_names) + ("," if len(model_names) == 1 else ""),
            training=training,
        )
    )
    return "".join(parts)
