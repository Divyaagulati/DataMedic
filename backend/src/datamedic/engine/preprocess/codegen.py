"""Generated Python code for validated steps (ML_ENGINE_DESIGN §9; PHASE4_PLAN §9).

The generated module is self-contained: it embeds ``preprocess.runtime`` verbatim (the same
algorithms the platform runs) followed by one small function per step and ``preprocess()``.
It needs only NumPy, pandas and scikit-learn and never loads stored fitted objects: every
fitted step is refit from the data.

Safety: parameters and column names are emitted only as ``repr`` of JSON primitives (strings,
numbers, booleans, lists of those), so no user-supplied text is ever interpreted as code.
Comments and docstrings contain only catalogue text (op names, versions), never column names.

Part A emits the step functions and ``preprocess()``; Part E wraps them into a full
``pipeline.py`` that loads the original file and replays a version's lineage.
"""

import math
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from datamedic.engine import ENGINE_VERSION
from datamedic.engine.preprocess.catalog import SAMPLE_WEIGHT, Limits
from datamedic.engine.preprocess.validate import ValidatedStep

# The runtime's source is read from its file, not imported: rendering code needs no
# pandas, so the API process can generate code (ARCHITECTURE: the API never imports
# data libraries). The text is exactly what inspect.getsource(runtime) returns.
RUNTIME_SOURCE_PATH = Path(__file__).with_name("runtime.py")


def runtime_source() -> str:
    return RUNTIME_SOURCE_PATH.read_text(encoding="utf-8")


_HEADER = '''"""DataMedic preprocessing steps (generated by DataMedic engine {engine}).

preprocess(fit_df, df) fits each step on fit_df (after the earlier steps) and applies it to
df. To avoid leakage when evaluating a model, pass only the training rows as fit_df. Passing
one table as both reproduces a committed version (whose fitted steps used all rows).

prepare_training(fit_df) returns the table to fit a model on: fit_df after every step, with
resampling or class weights (if any) applied to these training rows only. Never resample
validation or test rows: transform them with preprocess(fit_df, df).

Columns starting with '_dm_' are never model inputs: '_dm_row_id' identifies rows (negative
for rows added by resampling) and '_dm_sample_weight' is a per-row training weight.
"""
'''

_FOOTER = '''

STEPS = ({steps})
TRAINING_STEP = {training}


def preprocess(fit_df, df=None):
    """Fit every step on fit_df and apply it to df (default: fit_df). Resampling and class
    weights never change df: they apply only in prepare_training."""
    if df is None:
        df = fit_df
    for make_step in STEPS:
        apply = make_step(fit_df)
        fit_df, df = apply(fit_df), apply(df)
    return df


def prepare_training(fit_df):
    """The training table: fit_df after every step, then resampled or weighted (training
    rows only)."""
    df = preprocess(fit_df)
    return df if TRAINING_STEP is None else TRAINING_STEP(df)
'''


class CodegenError(ValueError):
    pass


def literal(value: Any) -> str:
    """``repr`` of a JSON primitive, a list of them, or a dict with text keys (used for an
    outlier rule's parameters). Anything else is refused."""
    if value is None or isinstance(value, bool | int | str):
        return repr(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise CodegenError("non-finite number")
        return repr(value)
    if isinstance(value, list | tuple):
        return "[" + ", ".join(literal(v) for v in value) + "]"
    if isinstance(value, dict):
        if not all(isinstance(k, str) for k in value):
            raise CodegenError("dict keys must be text")
        return "{" + ", ".join(f"{literal(k)}: {literal(v)}" for k, v in value.items()) + "}"
    raise CodegenError(f"unsupported parameter type {type(value).__name__}")


def _step_source(number: int, v: ValidatedStep) -> str:
    op, p = v.step.op, v.step.params
    cols = literal(list(v.step.columns))
    if op in ("impute.mean", "impute.median"):
        strategy = literal(op.split(".")[1])
        fit = f"    state = fit_simple_numeric(fit_df, {cols}, {strategy})\n"
        apply = f"apply_simple_numeric(df, {cols}, state)"
    elif op == "impute.mode":
        fit = f"    state = fit_mode(fit_df, {cols})\n"
        apply = f"apply_mode(df, {cols}, state)"
    elif op == "impute.constant":
        fit = ""
        apply = f"apply_constant(df, {cols}, {literal(p['fill_value'])})"
    elif op == "impute.knn":
        fit = (
            f"    state = fit_knn(fit_df, {cols}, {literal(p['predictors'])}, "
            f"{literal(p['n_neighbors'])}, {literal(p['weights'])})\n"
        )
        apply = f"apply_knn(df, {cols}, state)"
    elif op == "impute.iterative":
        fit = (
            f"    state = fit_iterative(fit_df, {cols}, {literal(p['predictors'])}, "
            f"{literal(p['max_iter'])}, {literal(p['clip_to_fit_range'])}, SEED)\n"
        )
        apply = f"apply_iterative(df, {cols}, state)"
    elif op == "missing.indicator":
        fit = ""
        apply = f"apply_indicator(df, {cols})"
    elif op in ("outliers.flag", "outliers.cap"):
        rule = {k: v for k, v in p.items() if k != "method"}
        fit = (
            f"    state = fit_bounds(fit_df, {cols}, {literal(p['method'])}, {literal(rule)}, "
            f"{literal(Limits.OUTLIER_MIN_VALUES)})\n"
        )
        func = "apply_outlier_flag" if op == "outliers.flag" else "apply_outlier_cap"
        apply = f"{func}(df, {cols}, state)"
    elif op == "outliers.signed_log":
        fit = ""
        apply = f"apply_signed_log(df, {cols})"
    elif op == "outliers.isolation_forest_flag":
        fit = (
            f"    state = fit_isolation_forest(fit_df, {cols}, {literal(p['n_estimators'])}, "
            f"{literal(p['contamination'])}, SEED, {literal(Limits.IF_MIN_ROWS)})\n"
        )
        apply = f"apply_isolation_forest(df, {cols}, {literal(p['output_column'])}, state)"
    elif op == "encode.onehot":
        fit = (
            f"    state = fit_onehot(fit_df, {cols}, {literal(p['max_categories'])}, "
            f"{literal(p['name_by'])})\n"
        )
        apply = f"apply_onehot(df, {cols}, state, {literal(p['handle_unknown'])})"
    elif op == "encode.ordinal":
        column, order = literal(v.step.columns[0]), literal(p["order"])
        fit = f"    fit_ordinal(fit_df, {column}, {order})\n"
        apply = f"apply_ordinal(df, {column}, {order}, {literal(p['handle_unknown'])})"
    elif op == "encode.frequency":
        fit = f"    state = fit_frequency(fit_df, {cols})\n"
        apply = f"apply_frequency(df, {cols}, state)"
    elif op in ("scale.standard", "scale.minmax", "scale.robust"):
        kind = literal(op.split(".")[1])
        clip = literal(bool(p.get("clip", False)))
        fit = f"    state = fit_scaler(fit_df, {cols}, {kind}, {clip})\n"
        apply = f"apply_scaler(df, {cols}, state)"
    elif op == "scale.none":
        fit = ""
        apply = "apply_no_scaling(df)"
    elif op == "transform.log":
        base = literal(p["base"])
        fit = f"    apply_log(fit_df, {cols}, {base})  # refuses zero or negative values\n"
        apply = f"apply_log(df, {cols}, {base})"
    elif op == "transform.log1p":
        fit = f"    apply_log1p(fit_df, {cols})  # refuses values of -1 or below\n"
        apply = f"apply_log1p(df, {cols})"
    elif op == "transform.yeo_johnson":
        fit = (
            f"    state = fit_yeo_johnson(fit_df, {cols}, {literal(Limits.TRANSFORM_MIN_VALUES)})\n"
        )
        apply = f"apply_yeo_johnson(df, {cols}, state)"
    elif op == "transform.quantile":
        fit = (
            f"    state = fit_quantile(fit_df, {cols}, {literal(p['n_quantiles'])}, "
            f"{literal(p['output_distribution'])}, SEED, {literal(Limits.QUANTILE_SUBSAMPLE)}, "
            f"{literal(Limits.TRANSFORM_MIN_VALUES)})\n"
        )
        apply = f"apply_quantile(df, {cols}, state)"
    elif op == "select.variance":
        fit = (
            f"    state = fit_variance(fit_df, {cols}, {literal(float(p['threshold']))}, "
            f"{literal(p['action'])}, {literal(p['keep'])}, {literal(p['role_kept'])})\n"
        )
        apply = 'apply_drop_columns(df, state["drop"])'
    elif op == "select.correlation":
        fit = (
            f"    state = fit_correlation(fit_df, {cols}, {literal(float(p['threshold']))}, "
            f"{literal(p['method'])}, {literal(p['keep'])}, {literal(p['role_kept'])}, "
            f"{literal(Limits.CORR_MIN_PAIRS)})  # proposals only\n"
        )
        apply = "apply_drop_columns(df, [])"
    elif op == "select.mutual_information":
        fit = (
            f"    state = fit_mutual_information(fit_df, {cols}, {literal(p['target'])}, "
            f"{literal(p['task'])}, {literal(p['discrete'])}, {literal(p['n_neighbors'])}, "
            f"{literal(p['k'])}, {literal(p['action'])}, {literal(p['keep'])}, "
            f"{literal(p['role_kept'])}, SEED, {literal(Limits.SELECT_MIN_ROWS)})\n"
        )
        apply = 'apply_drop_columns(df, state["drop"])'
    elif op == "select.univariate":
        fit = (
            f"    state = fit_univariate(fit_df, {cols}, {literal(p['target'])}, "
            f"{literal(p['task'])}, {literal(p['test'])}, {literal(p['k'])}, "
            f"{literal(p['action'])}, {literal(p['keep'])}, {literal(p['role_kept'])}, "
            f"{literal(Limits.SELECT_MIN_ROWS)}, {literal(Limits.CHI2_MAX_LEVELS)})\n"
        )
        apply = 'apply_drop_columns(df, state["drop"])'
    elif op == "select.drop_columns":
        fit = ""
        apply = f"apply_drop_columns(df, {cols})"
    elif v.spec.kind == "training_only":
        # Rows other than the training table are never changed; see training_step().
        fit = f"    fit_class_counts(fit_df, {literal(p['target'])})\n"
        apply = "df.copy()"
    else:
        raise CodegenError(f"no code template for {op}")
    return (
        f"\n\ndef step_{number}(fit_df):\n"
        f"    # {op} {v.spec.version}\n"
        f"{fit}"
        f"    return lambda df: {apply}\n"
    )


def _training_source(v: ValidatedStep) -> str:
    """The training-only step: applied by prepare_training to the training rows only."""
    op, p = v.step.op, v.step.params
    target = literal(p["target"])
    if op == "imbalance.class_weight":
        body = (
            f"    state = fit_class_counts(df, {target})\n"
            f"    return resample_class_weight(df, {target}, state, {literal(SAMPLE_WEIGHT)})\n"
        )
    elif op in ("imbalance.random_oversample", "imbalance.random_undersample"):
        method = "oversample" if op.endswith("oversample") else "undersample"
        body = (
            f"    return resample_random(df, {target}, {literal(method)}, "
            f"{literal(p['sampling_strategy'])}, SEED, "
            f"{literal(Limits.RESAMPLE_MAX_OUTPUT_ROWS)}, "
            f"{literal(Limits.RESAMPLE_MAX_OUTPUT_CELLS)})\n"
        )
    elif op == "imbalance.smote":
        body = (
            f"    return resample_smote(df, {target}, {literal(p['passthrough'])}, "
            f"{literal(p['sampling_strategy'])}, {literal(p['k_neighbors'])}, SEED, "
            f"{literal(Limits.SMOTE_MAX_FEATURES)}, {literal(Limits.RESAMPLE_MAX_OUTPUT_ROWS)}, "
            f"{literal(Limits.RESAMPLE_MAX_OUTPUT_CELLS)})\n"
        )
    else:
        raise CodegenError(f"no code template for {op}")
    return f"\n\ndef training_step(df):\n    # {op} {v.spec.version} (training rows only)\n{body}"


def render_steps(steps: Sequence[ValidatedStep], *, seed: int = 0) -> str:
    """Return a standalone Python module implementing ``steps``."""
    if not isinstance(seed, int) or isinstance(seed, bool):
        raise CodegenError("seed must be an integer")
    parts = [
        _HEADER.format(engine=ENGINE_VERSION),
        runtime_source(),
        f"\n\nSEED = {literal(seed)}\n",
    ]
    names = []
    training = "None"
    for number, v in enumerate(steps, start=1):
        parts.append(_step_source(number, v))
        names.append(f"step_{number}")
        if v.spec.kind == "training_only":
            parts.append(_training_source(v))
            training = "training_step"
    steps_tuple = ", ".join(names) + ("," if len(names) == 1 else "")
    parts.append(_FOOTER.format(steps=steps_tuple, training=training))
    return "".join(parts)
